import { useState } from "react"
import { inputStyles } from "./inputStyles"

function MentorMatch({ mentors, onRequest }) {
  const [goal, setGoal] = useState("")
  const [matches, setMatches] = useState([])
  const [isLoading, setIsLoading] = useState(false)
  const [error, setError] = useState("")

  async function handleSubmit(event) {
    event.preventDefault()

    if (goal.trim().length < 10) {
      setError("Please describe your goal in at least 10 characters.")
      setMatches([])
      return
    }

    setIsLoading(true)
    setError("")
    setMatches([])

    try {
      const response = await fetch("/api/match", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ goal }),
      })
      const data = await response.json()

      if (!response.ok) {
        setError(data.error || "Something went wrong. Please try again.")
        return
      }

      setMatches(data.matches)
    } catch {
      setError("Couldn't reach the matching service. Please check your connection and try again.")
    } finally {
      setIsLoading(false)
    }
  }

  return (
    <section className="mb-10 rounded-2xl bg-indigo-50 p-6 ring-1 ring-indigo-100">
      <h2 className="text-lg font-semibold text-slate-900">
        Not sure who to pick? Let AI suggest a mentor
      </h2>
      <p className="mt-1 text-sm text-slate-600">
        Describe your goal and we'll suggest up to 3 mentors who fit.
      </p>

      <form onSubmit={handleSubmit} className="mt-4 flex flex-col gap-3 sm:flex-row">
        <label htmlFor="goal" className="sr-only">
          Your goal
        </label>
        <input
          id="goal"
          type="text"
          value={goal}
          onChange={(event) => setGoal(event.target.value)}
          maxLength={500}
          placeholder="e.g. I'm a data science grad who wants to work in healthcare AI"
          className={inputStyles}
        />
        <button
          type="submit"
          disabled={isLoading}
          className="shrink-0 rounded-lg bg-indigo-600 px-4 py-2 text-sm font-semibold text-white hover:bg-indigo-700 disabled:cursor-not-allowed disabled:opacity-60"
        >
          {isLoading ? "Finding mentors..." : "Find my mentor"}
        </button>
      </form>

      {error && (
        <p role="alert" className="mt-3 text-sm text-red-600">
          {error}
        </p>
      )}

      {matches.length > 0 && (
        <>
          <ul className="mt-5 space-y-3">
            {matches.map((match) => {
              const mentor = mentors.find((item) => item.id === match.id)

              if (!mentor) {
                return null
              }

              return (
                <li
                  key={match.id}
                  className="flex flex-col gap-3 rounded-xl bg-white p-4 ring-1 ring-slate-200 sm:flex-row sm:items-center sm:justify-between"
                >
                  <div>
                    <p className="font-semibold text-slate-900">
                      {mentor.name}{" "}
                      <span className="font-normal text-slate-600">· {mentor.role}</span>
                    </p>
                    <p className="mt-1 text-sm text-slate-700">{match.reason}</p>
                  </div>
                  <button
                    type="button"
                    onClick={() => onRequest(mentor)}
                    className="shrink-0 rounded-lg border border-indigo-600 px-3 py-1.5 text-sm font-semibold text-indigo-700 hover:bg-indigo-50"
                  >
                    Request a session
                  </button>
                </li>
              )
            })}
          </ul>
          <p className="mt-3 text-xs text-slate-500">
            Suggestions are generated by AI and may not be perfect.
          </p>
        </>
      )}
    </section>
  )
}

export default MentorMatch